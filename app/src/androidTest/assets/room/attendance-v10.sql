CREATE TABLE Semesters (
    id BLOB NOT NULL,
    name TEXT NOT NULL,
    startDate INTEGER NOT NULL,
    endDate INTEGER,
    targetAttendance INTEGER NOT NULL,
    isArchived INTEGER NOT NULL,
    PRIMARY KEY (id)
);
CREATE TABLE Subjects (
    id BLOB NOT NULL,
    name TEXT NOT NULL,
    semesterId BLOB NOT NULL,
    startDate INTEGER NOT NULL,
    isEnded INTEGER NOT NULL,
    color TEXT NOT NULL,
    professor TEXT,
    roomNo TEXT,
    notes TEXT,
    totalClasses INTEGER NOT NULL,
    attendedClasses INTEGER NOT NULL,
    minAttendance INTEGER NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (semesterId) REFERENCES Semesters(id) ON UPDATE NO ACTION ON DELETE CASCADE
);
CREATE INDEX index_Subjects_semesterId ON Subjects (semesterId);
CREATE TABLE SessionRecords (
    id BLOB NOT NULL,
    subjectId BLOB NOT NULL,
    orderNo INTEGER NOT NULL,
    dayOfWeek INTEGER NOT NULL,
    startDate INTEGER NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (subjectId) REFERENCES Subjects(id) ON UPDATE NO ACTION ON DELETE CASCADE
);
CREATE INDEX index_SessionRecords_subjectId ON SessionRecords (subjectId);
CREATE TABLE AttendanceRecords (
    id BLOB NOT NULL,
    subjectId BLOB NOT NULL,
    sessionId BLOB,
    date INTEGER NOT NULL,
    status TEXT,
    classType TEXT NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (subjectId) REFERENCES Subjects(id) ON UPDATE NO ACTION ON DELETE CASCADE
);
CREATE INDEX index_AttendanceRecords_subjectId ON AttendanceRecords (subjectId);
